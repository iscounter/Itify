package com.openreachtube.app.domain.model

/** Pure domain types shared across screens (original definitions). */
data class VideoItem(
    val id: String,
    val title: String,
    val uploader: String,
    val uploaderUrl: String? = null,
    val thumbnailUrl: String? = null,
    val durationSeconds: Long = 0,
    val viewCount: Long = -1,
    val uploadDate: String? = null,
    val isShort: Boolean = false,
    /** Seconds already watched (continue-playing progress bar). */
    val progressSeconds: Long = 0,
)

data class ChannelInfo(
    val id: String,
    val name: String,
    val avatarUrl: String? = null,
    val subscriberCount: Long = -1,
    val description: String? = null,
)

data class CommentItem(
    val id: String,
    val author: String,
    val text: String,
    val likeCount: Long = -1,
    val publishedAgo: String? = null,
)

data class SubtitleItem(
    val languageTag: String,
    val url: String,
    val isAutoGenerated: Boolean,
)

data class StreamBundle(
    val videoId: String,
    val title: String,
    val uploader: String,
    val uploaderUrl: String? = null,
    val thumbnailUrl: String? = null,
    val durationSeconds: Long = 0,
    val viewCount: Long = -1,
    val uploadDate: String? = null,
    val streams: List<StreamOption>,
    val hlsUrl: String? = null,
    val subtitles: List<SubtitleItem>,
    val related: List<VideoItem> = emptyList(),
)

data class StreamOption(
    val url: String,
    val mimeType: String,
    val width: Int = 0,
    val height: Int = 0,
    val averageBitrate: Long = 0,
    val isAudioOnly: Boolean = false,
    val isVideoOnly: Boolean = false,
    /** poToken to attach to the stream request, when required by the client. */
    val poToken: String? = null,
)

data class SponsorSegment(
    val startSeconds: Float,
    val endSeconds: Float,
    /** sponsor, selfpromo, interaction, intro, outro, music_offtopic, preview */
    val category: String,
    val uuid: String,
)

data class ShortsFeedResult(
    val items: List<VideoItem>,
    val continuation: String? = null,
)

data class PaginatedList<T>(
    val items: List<T>,
    val nextPageUrl: String? = null,
)

enum class SearchTab { ALL, VIDEOS, CHANNELS, SHORTS }
enum class SearchSort { RELEVANCE, LATEST, POPULAR, OLDEST, NEWEST, MOST_VIEWED, TOP_RATED }
